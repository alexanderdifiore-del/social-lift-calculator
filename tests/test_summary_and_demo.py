import pandas as pd
import pytest

from lollie.analysis.baseline import AnalysisSettings, analyze_campaign_window
from lollie.demo import C1, DEMO_ARTIST, DEMO_LABEL, demo_paid_raw, demo_streams_raw, load_demo, write_sample_files
from lollie.paid.metrics import aggregate_kpis, results_by_type
from lollie.summary import build_summary
from lollie.ui.paid_sections import by_country_table
from lollie.ui.sections import results_sentences

FORBIDDEN_CLAIMS = ("caused", "because of the ads", "attributed to", "proves", "drove ", "generated by the playlist")


@pytest.fixture(scope="module")
def demo():
    return load_demo()


def test_demo_data_is_synthetic_deterministic_and_imports_cleanly(demo):
    paid, streams, issues = demo
    assert "Synthetic" in DEMO_LABEL and "synthetic" in DEMO_ARTIST
    assert not [i for i in issues if i.level == "error"]
    assert set(paid["artist"]) == {DEMO_ARTIST} and set(streams["artist"]) == {DEMO_ARTIST}
    assert demo_paid_raw().equals(demo_paid_raw()) and demo_streams_raw().equals(demo_streams_raw())


def test_sample_files_are_written_and_readable(tmp_path):
    paths = write_sample_files(tmp_path)
    assert {p.name for p in paths} == {
        "sample_wavo_paid_media.csv", "sample_streaming_daily.csv", "sample_streaming_daily.xlsx", "sample_playlist_track_list.csv",
    }
    assert pd.read_csv(tmp_path / "sample_wavo_paid_media.csv").shape[0] == 189
    assert pd.read_excel(tmp_path / "sample_streaming_daily.xlsx").shape[0] == pd.read_csv(tmp_path / "sample_streaming_daily.csv").shape[0]


def test_paid_kpis_count_budget_once_and_never_mix_result_types(demo):
    paid, _, _ = demo
    rows = paid[paid["campaign_name"] == C1]
    kpis = aggregate_kpis(rows)
    assert kpis["budget"] == pytest.approx(4200 + 1600 + 1000 + 1400 + 800 + 1800 + 1200)
    assert kpis["landing_page_views"] == pytest.approx(rows["landing_page_views"].sum())
    results = results_by_type(rows)
    assert set(results["family"]) == {"landing_page_views", "video_views"}
    assert results["Results"].sum() == pytest.approx(rows["results"].sum())
    assert any("not combined" in s for s in results_sentences(results, "USD"))


def test_by_country_table_matches_paid_totals(demo):
    paid, _, _ = demo
    rows = paid[paid["campaign_name"] == C1]
    table = by_country_table(rows)
    assert table["Spend"].sum() == pytest.approx(rows["spend"].sum())
    assert "United States" in table["Country"].tolist()


def _summary(analysis=None, **overrides):
    args = dict(
        campaign="C1", scope_label="Song", currency="USD",
        kpis={"spend": 1000.0, "impressions": 50000.0, "clicks": 500.0, "landing_page_views": 300.0, "cpm": 20.0, "cpc": 2.0},
        results_text=[], analysis=analysis, market_table=pd.DataFrame(), rank_note=None, relationship=None,
        overlap_notes=[], data_notes=[],
    )
    args.update(overrides)
    return build_summary(**args)


def test_summary_states_numbers_and_the_observational_limit():
    idx = pd.date_range("2026-01-01", periods=70)
    series = pd.Series(1000.0, index=idx)
    series.loc["2026-02-10":"2026-02-20"] *= 1.2
    analysis = analyze_campaign_window(series, pd.Timestamp("2026-02-10"), pd.Timestamp("2026-02-20"), AnalysisSettings())
    text = _summary(analysis).to_markdown("Test")
    assert "+20%" in text and "$1,000" in text
    assert "does not show that the advertising caused the change" in text
    body = text.lower().replace("does not show that the advertising caused the change", "")
    assert not any(claim in body for claim in FORBIDDEN_CLAIMS)


def test_summary_explains_when_no_comparison_is_possible():
    idx = pd.date_range("2026-02-08", periods=20)
    analysis = analyze_campaign_window(pd.Series(1000.0, index=idx), pd.Timestamp("2026-02-10"), pd.Timestamp("2026-02-15"))
    text = _summary(analysis).to_markdown()
    assert "not available" in text.lower()


def test_summary_notes_unverified_playlists_and_source_streams():
    text = _summary(None, multi_track=True, membership_verified=False, source_attributed_present=True).to_markdown()
    assert "not been marked as verified" in text
    assert "shown separately" in text


def test_summary_lists_markets_with_positive_and_limited_change():
    table = pd.DataFrame(
        {
            "Market": ["United States", "Germany"], "Paid activity": ["Paid", "Paid"],
            "Change vs baseline": [0.3, 0.02],
        }
    )
    text = _summary(None, market_table=table).to_markdown()
    assert "United States" in text and "Germany (+2%)" in text
